type PageProps = {
  params: Promise<{
    id: string;
  }>;
};

const DetailMagazin = async ({ params }: PageProps) => {
  const { id } = await params;

  const article = articles.find((item) => item.id === Number(id));

  if (!article) {
    return (
      <div className="flex min-h-[50vh] items-center justify-center">
        <h1 className="text-2xl font-black text-slate-900">مقاله پیدا نشد</h1>
      </div>
    );
  }

  return (
    <DetailMagazinComponent
      img={article.img}
      title={article.title}
      newAuth={article.nameAuth}
      date={article.date}
      description={article.description}
    />
  );
};

export default DetailMagazin;
